-- Run after the guided-round migration in a transaction, then roll it back.
do $$
declare
  room jsonb; host jsonb; state jsonb; room_code text; host_key text; tv_key text; test_room_id uuid;
  a uuid; b uuid; c uuid; d uuid; e uuid; f uuid; role_text text;
begin
  room := public.game_create(); room_code := room->>'code'; tv_key := room->>'token';
  host := public.game_join(room_code, 'host'); host_key := host->>'token';
  perform public.game_join(room_code, 'player', 'Alice');
  perform public.game_join(room_code, 'player', 'Bob');
  perform public.game_join(room_code, 'player', 'Charlie');
  perform public.game_join(room_code, 'player', 'Dana');
  perform public.game_join(room_code, 'player', 'Eve');
  perform public.game_join(room_code, 'player', 'Frank');
  select id into test_room_id from public.game_rooms where code = room_code;
  select id into a from public.game_players where game_players.room_id = test_room_id and name = 'Alice';
  select id into b from public.game_players where game_players.room_id = test_room_id and name = 'Bob';
  select id into c from public.game_players where game_players.room_id = test_room_id and name = 'Charlie';
  select id into d from public.game_players where game_players.room_id = test_room_id and name = 'Dana';
  select id into e from public.game_players where game_players.room_id = test_room_id and name = 'Eve';
  select id into f from public.game_players where game_players.room_id = test_room_id and name = 'Frank';
  perform public.game2_command(room_code, host_key, 'assign', '2');
  update public.game_players set role = case when id in (c,d) then 'traitor' else 'faithful' end where game_players.room_id = test_room_id;
  perform public.game2_command(room_code, host_key, 'start_mission');
  state := public.game2_state(room_code, 'host', null, host_key);
  if state->>'phase' <> 'mission' or (state->>'phaseEndsAt')::timestamptz < now() + interval '4 minutes 59 seconds' then raise exception 'Mission timer failed'; end if;
  perform public.game2_command(room_code, host_key, 'skip_mission');
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'mission_complete' or state->>'phaseEndsAt' is not null then raise exception 'Mission skip did not pause'; end if;
  perform public.game2_command(room_code, host_key, 'start_discussion');
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'discussion' or (state->>'phaseEndsAt')::timestamptz < now() + interval '4 minutes 59 seconds' then raise exception 'Discussion timer failed'; end if;
  update public.game_rooms set phase_ends_at = now() - interval '1 second' where id = test_room_id;
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'vote' then raise exception 'Discussion did not advance'; end if;
  perform public.game2_vote(room_code, 'Alice', b);
  perform public.game2_vote(room_code, 'Bob', a);
  perform public.game2_vote(room_code, 'Charlie', a);
  perform public.game2_vote(room_code, 'Dana', a);
  perform public.game2_vote(room_code, 'Eve', b);
  perform public.game2_vote(room_code, 'Frank', b);
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'defense' or jsonb_array_length(state->'candidates') <> 2 then raise exception 'Tie did not start defense'; end if;
  update public.game_rooms set phase_ends_at = now() - interval '3 minutes' where id = test_room_id;
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'revote' then raise exception 'Defense did not advance to revote'; end if;
  begin
    perform public.game2_vote(room_code, 'Alice', c);
    raise exception 'Invalid revote target was accepted';
  exception when others then if sqlerrm <> 'Choose an eligible player' then raise; end if; end;
  perform public.game2_vote(room_code, 'Alice', b);
  perform public.game2_vote(room_code, 'Bob', a);
  perform public.game2_vote(room_code, 'Charlie', a);
  perform public.game2_vote(room_code, 'Dana', a);
  perform public.game2_vote(room_code, 'Eve', b);
  perform public.game2_vote(room_code, 'Frank', b);
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'defense' then raise exception 'A tied revote did not restart defenses'; end if;
  update public.game_rooms set phase_ends_at = now() - interval '3 minutes' where id = test_room_id;
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'revote' then raise exception 'Repeated defenses did not advance to revote'; end if;
  perform public.game2_vote(room_code, 'Alice', b);
  perform public.game2_vote(room_code, 'Bob', a);
  perform public.game2_vote(room_code, 'Charlie', a);
  perform public.game2_vote(room_code, 'Dana', a);
  perform public.game2_vote(room_code, 'Eve', a);
  perform public.game2_vote(room_code, 'Frank', b);
  state := public.game2_state(room_code, 'player', 'Alice');
  if state->>'phase' <> 'banishment' or not (state->>'isSelected')::boolean then raise exception 'Banishment selection failed'; end if;
  if public.game2_state(room_code, 'host', null, host_key)->>'revealedRole' is not null then raise exception 'Role revealed too early'; end if;
  begin
    perform public.game2_reveal(room_code, 'Bob');
    raise exception 'Wrong player revealed role';
  exception when others then if sqlerrm <> 'Only the banished player can reveal their role' then raise; end if; end;
  perform public.game2_reveal(room_code, 'Alice');
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'revealedRole' <> 'faithful' then raise exception 'Role reveal failed'; end if;
  perform public.game2_command(room_code, host_key, 'start_night');
  perform public.game2_night_choice(room_code, 'Charlie', e);
  perform public.game2_night_choice(room_code, 'Dana', f);
  begin
    perform public.game2_night_lock(room_code, 'Charlie');
    raise exception 'Disagreement was accepted';
  exception when others then if sqlerrm <> 'All traitors must choose the same victim before locking in' then raise; end if; end;
  perform public.game2_night_choice(room_code, 'Dana', e);
  state := public.game2_state(room_code, 'player', 'Charlie');
  if jsonb_array_length(state->'nightChoices') <> 2 then raise exception 'Traitor choices missing'; end if;
  if public.game2_state(room_code, 'host', null, host_key) ? 'nightChoices' then raise exception 'Night choices leaked to host'; end if;
  perform public.game2_night_lock(room_code, 'Charlie');
  perform public.game2_night_lock(room_code, 'Dana');
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'blindfold' or (state->>'phaseEndsAt')::timestamptz < now() + interval '39 seconds' then raise exception 'Blindfold countdown failed'; end if;
  if (select status from public.game_players where id = e) <> 'alive' then raise exception 'Victim marked out before morning'; end if;
  update public.game_rooms set phase_ends_at = now() - interval '1 second' where id = test_room_id;
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'morning' or state->>'selectedPlayer' <> 'Eve' then raise exception 'Morning announcement failed'; end if;
  if (select status from public.game_players where id = e) <> 'killed' then raise exception 'Victim not marked killed'; end if;
  perform public.game2_command(room_code, host_key, 'start_mission');
  update public.game_rooms set phase_ends_at = now() - interval '10 minutes' where id = test_room_id;
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'mission_complete' or state->>'phaseEndsAt' is not null then raise exception 'Expired mission did not pause'; end if;
  perform public.game2_command(room_code, host_key, 'start_discussion');
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'discussion' or (state->>'phaseEndsAt')::timestamptz < now() + interval '4 minutes 59 seconds' then raise exception 'Discussion did not start from host action'; end if;
end $$;

do $$
declare
  room jsonb; host jsonb; state jsonb; room_code text; host_key text; tv_key text; test_room_id uuid;
  a uuid; b uuid; e uuid; first_defender text; second_defender text;
begin
  room := public.game_create(); room_code := room->>'code'; tv_key := room->>'token';
  host := public.game_join(room_code, 'host'); host_key := host->>'token';
  perform public.game_join(room_code, 'player', 'Alice');
  perform public.game_join(room_code, 'player', 'Bob');
  perform public.game_join(room_code, 'player', 'Charlie');
  perform public.game_join(room_code, 'player', 'Dana');
  perform public.game_join(room_code, 'player', 'Eve');
  perform public.game_join(room_code, 'player', 'Frank');
  select id into test_room_id from public.game_rooms where code = room_code;
  select id into a from public.game_players where room_id = test_room_id and name = 'Alice';
  select id into b from public.game_players where room_id = test_room_id and name = 'Bob';
  select id into e from public.game_players where room_id = test_room_id and name = 'Eve';
  perform public.game2_command(room_code, host_key, 'assign', '2');
  perform public.game2_command(room_code, host_key, 'start_mission');
  perform public.game2_command(room_code, host_key, 'skip_mission');
  perform public.game2_command(room_code, host_key, 'start_discussion');
  update public.game_rooms set phase_ends_at = now() - interval '1 second' where id = test_room_id;
  perform public.game2_state(room_code, 'tv', null, tv_key);
  perform public.game2_vote(room_code, 'Alice', b);
  perform public.game2_vote(room_code, 'Bob', a);
  perform public.game2_vote(room_code, 'Charlie', b);
  perform public.game2_vote(room_code, 'Dana', e);
  perform public.game2_vote(room_code, 'Eve', a);
  perform public.game2_vote(room_code, 'Frank', e);
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'defense' or jsonb_array_length(state->'candidates') <> 3 or state->>'defender' not in ('Alice', 'Bob', 'Eve') then raise exception 'Three-way tie did not start first defense'; end if;
  first_defender := state->>'defender';
  update public.game_rooms set phase_ends_at = now() - interval '1 second' where id = test_room_id;
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'defense' or state->>'defender' not in ('Alice', 'Bob', 'Eve') or state->>'defender' = first_defender then raise exception 'Second defense failed'; end if;
  second_defender := state->>'defender';
  update public.game_rooms set phase_ends_at = now() - interval '1 second' where id = test_room_id;
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'defense' or state->>'defender' not in ('Alice', 'Bob', 'Eve') or state->>'defender' in (first_defender, second_defender) then raise exception 'Third defense failed'; end if;
  update public.game_rooms set phase_ends_at = now() - interval '1 second' where id = test_room_id;
  state := public.game2_state(room_code, 'tv', null, tv_key);
  if state->>'phase' <> 'revote' or jsonb_array_length(state->'candidates') <> 3 then raise exception 'Three-way revote failed'; end if;
end $$;
